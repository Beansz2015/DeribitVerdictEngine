# ------------------------------------------------------------------ descriptive cell
def q5(v):
    s = sorted(v)
    return "/".join("%.1f" % pctl(s, q) for q in (10, 25, 50, 75, 90))

def cell_geom(rows):
    n = len(rows)
    sT = sum(r["T"] for r in rows); sS = sum(r["S"] for r in rows)
    ratios = sorted(r["T"] / r["S"] for r in rows)
    return {"n": n, "Tq": q5([r["T"] for r in rows]), "Sq": q5([r["S"] for r in rows]), "Tm": sT / n, "Sm": sS / n,
            "ratio": sT / sS, "medratio": pctl(ratios, 50), "TA": pctl(sorted(r["TA"] for r in rows), 50),
            "SA": pctl(sorted(r["SA"] for r in rows), 50), "atr": pctl(sorted(r["atr_bps"] for r in rows), 50)}

def cell_out(rows):
    n = len(rows)
    sT = sum(r["T"] for r in rows); sS = sum(r["S"] for r in rows); sW = sT + sS
    succ = 100.0 * sum(r["win"] for r in rows) / n
    stop = 100.0 * sum(r["lose"] for r in rows) / n
    tout = 100.0 * sum(r["open"] for r in rows) / n
    gbe = 100.0 * sS / sW
    nbe = 100.0 * (sS + n * FEE) / sW
    sw = 100.0 * sum(r["win"] * r["W"] for r in rows) / sW
    W = sW / n
    term1 = W * (sw - gbe) / 100.0
    tterm = sum(r["open"] * (r["S"] + r["mark"]) for r in rows) / n
    ev = sum(r["ev"] for r in rows) / n
    resid = ev - (term1 + tterm - FEE)
    return {"n": n, "succ": succ, "stop": stop, "tout": tout, "gbe": gbe, "nbe": nbe, "gedge": succ - gbe, "nedge": succ - nbe,
            "sw": sw, "wedge": sw - gbe, "W": W, "term1": term1, "tterm": tterm, "ev": ev, "resid": resid}

