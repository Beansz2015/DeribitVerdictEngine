# first by the trader 2026-09-18). Read: docs/q1d-tier-geometry-read-2026-09-24.md. Python 3 standard library only.
# Host-agnostic: no engine code, no settings write, no network. Vocabulary: docs/DeribitIndicatorProject.md section 5a.
#
# Question: success rate rises at the top score bins while net EV per trade does not. Is the rise bought with
# nearer targets (payoff down), or does the ladder carry direction information that the geometry spends?
#
# Inputs (gitignored, regenerated by the instrument, see the read's re-run section):
#   --rows        SwingFallbackRead --mode diagexport on the newest fetch (one line per swing read population row).
#   --prior-rows  The same export on the fetch the MEDIUM-tier diagnosis used (aws_fetch/20260913-153704). It defines
#                 the main population P0 (8,810 rows) and carries its H1/H2 halves unchanged.
#   --attr        SwingFallbackRead --mode rescore attribution (recomputed VPFR label), for the POC-fix slice.
#   --logs        analysis_log copies (pooled book, box live log), first timestamp wins, for SwingStopLong/Short.
#   settings.json (tracked, read-only): fees, stop bound, stop floor.
#
# Rules fixed before the first run:
#   * Populations: P0 = the prior read's rows (v51 edge to 2026-09-11), halves H1/H2 as the prior read.
#     H3 = rows from 2026-09-14 in --rows and not in P0: a forward segment, reported separately, never pooled with P0.
#     Sessions separate, never pooled for outcomes. Weekday rows only (the export applies the trading-week rule).
#   * Window: main window (NY 15 min, LONDON and ASIA 45 min), maker/maker fee from scoring.trade_costs. Carried 24 h
#     is secondary and for P0 only.
#   * Distances: per signal, bps of entry, from the logged Price and Placed* levels (export TBps, SBps).
#     Pooled rates use the section 5a sums: gross breakeven = sum S / sum (T + S); net breakeven = sum (S + fee) /
#     sum (T + S). Edges in pp. Net EV per trade from the export's candle-walk result.
#   * Coined here: distance-weighted success rate = sum over wins of (T + S) / sum (T + S). Exact identity per cell:
#       net EV = mean(T + S) x (distance-weighted success - gross breakeven) + timeout term - fee,
#       timeout term = (1/n) x sum over timeouts of (S + mark). Self-checked on every cell.
#   * Stop label, derived from the logged SwingStop and ATR by the shipped DG1 rule (SignalEmitter mode 0):
#       SWING_STOP if 0 < swing distance, >= 4 ticks and <= stop_max_atr_mult x ATR; STOP_CLAMPED if the swing
#       distance exceeds the bound; else FALLBACK_ATR. Self-check against the logged placed stop.
#   * CI: 95 % percentile bootstrap of whole UTC trading days, fixed seed, --resamples (default 10,000).
#   * Readable: n >= 100 in each group a comparison uses. Label rule: the census rule, copied from
#     tools/ops/medium_tier_diagnosis.py (first match wins): NOT READABLE -> CONFIRMED -> H1 FINDING, H2 SAME SIGN NOT
#     SIGNIFICANT -> H1 FINDING, H2 CONTRADICTS OR NOT READABLE -> DISCOVERY ONLY (H2) -> NO DIFFERENCE SHOWN.
#     The label is two-sided: it names the sign it found (d > 0 or d < 0), so both directions are tested at once.
#   * Geometry control: rows stratified by per-signal breakeven S / (T + S) quintile x (T + S) tercile, cut points
#     from the session's H1 rows (all tiers). Tier A re-weighted to tier B's stratum mix over strata where A has rows;
#     B restricted to the same strata. d_within = A_reweighted - B_covered.
#   * POC-fix slice (commit a6b33fe, not deployed): P0 rows whose verified recomputed VPFR label opens the POC tier
#     only under the fix (LONG + NEAR_HVN_SUPPORT, SHORT + NEAR_HVN_RESIST) and whose logged target is the ATR
#     fallback ("none"). A superset of the 143 population rows the fix moves (the ladder reaches the POC tier only
#     when swing and HVN fail). Sensitivity = the key comparisons with the slice removed.
#
# Run (from the repo root): see the read's re-run section.

