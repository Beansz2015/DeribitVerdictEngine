def strata_fn(sr):
    h1 = [r for r in sr if r["half"] == "H1"]
    pb = sorted(r["pbe"] for r in h1); wb = sorted(r["W"] for r in h1)
    qp = [pctl(pb, q) for q in (20, 40, 60, 80)]
    qw = [pctl(wb, q) for q in (100.0 / 3, 200.0 / 3)]
    def st(r):
        i = sum(1 for c in qp if r["pbe"] > c)
        j = sum(1 for c in qw if r["W"] > c)
        return i * 3 + j
    return st, qp, qw

def rw_stat_factory(K):
    def stat(s, c):
        # cells: 2k = A value in stratum k, 2k+1 = B value in stratum k
        cov = [k for k in range(K) if c[2 * k] > 0 and c[2 * k + 1] > 0]
        nb = sum(c[2 * k + 1] for k in cov)
        if nb == 0: return float("nan")
        arw = sum(c[2 * k + 1] / nb * s[2 * k] / c[2 * k] for k in cov)
        bcv = sum(s[2 * k + 1] for k in cov) / nb
        return arw - bcv
    return stat

def within(rows, ga, gb, val, st, K=15):
    def contribs(r):
        o = []
        k = st(r)
        if ga(r): o.append((2 * k, val(r)))
        if gb(r): o.append((2 * k + 1, val(r)))
        return o
    stat = rw_stat_factory(K)
    res = {"FULL": boot(rows, contribs, 2 * K, stat),
           "H1": boot([r for r in rows if r["half"] == "H1"], contribs, 2 * K, stat),
           "H2": boot([r for r in rows if r["half"] == "H2"], contribs, 2 * K, stat)}
    # readability on group totals
    for hn in res:
        pt, lo, hi, cnt = res[hn]
        res[hn] = (pt, lo, hi, [sum(cnt[0::2]), sum(cnt[1::2])])
    return res

